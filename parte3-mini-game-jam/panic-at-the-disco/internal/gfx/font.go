// DrawText renders retro pixel text with optional scaling and shadow.
func DrawText(screen *ebiten.Image, text string, x, y float64, scale float64, col color.RGBA, shadow bool) {
	upper := strings.ToUpper(text)
	charW := 6.0 * scale
	curX := x

	if shadow {
		shadowCol := color.RGBA{0, 0, 0, 190}
		DrawText(screen, text, x+scale, y+scale, scale, shadowCol, false)
	}

	for _, ch := range upper {
		rows, ok := fontGlyphs[ch]
		if !ok {
			rows = fontGlyphs['?']
		}

		for r := 0; r < 7; r++ {
			rowBits := rows[r]
			for c := 0; c < 5; c++ {
				// Most significant bit of 5 bits is at 0x10
				if (rowBits & (0x10 >> c)) != 0 {
					px := float32(curX + float64(c)*scale)
					py := float32(y + float64(r)*scale)
					vector.DrawFilledRect(screen, px, py, float32(scale), float32(scale), col, false)
				}
			}
		}
		curX += charW
	}
}

// MeasureText returns the pixel width of rendered text at a given scale.
func MeasureText(text string, scale float64) float64 {
	return float64(len(text)) * 6.0 * scale
}
